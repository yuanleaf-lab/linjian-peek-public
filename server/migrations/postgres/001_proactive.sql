CREATE TABLE IF NOT EXISTS schema_migrations (
    version integer PRIMARY KEY,
    applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS manual_events (
    id uuid PRIMARY KEY,
    device_id text NOT NULL CHECK (length(device_id) BETWEEN 1 AND 100),
    title text NOT NULL CHECK (length(title) BETWEEN 1 AND 100),
    message text NOT NULL CHECK (length(message) BETWEEN 1 AND 1000),
    due_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    status text NOT NULL CHECK (status IN ('active','cancelled')),
    revision integer NOT NULL DEFAULT 1 CHECK (revision >= 1),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CHECK (expires_at > due_at)
);
CREATE INDEX IF NOT EXISTS manual_events_due ON manual_events(due_at,id) WHERE status='active';

CREATE TABLE IF NOT EXISTS proactive_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id text NOT NULL,
    event_id text NOT NULL,
    topic text NOT NULL,
    title text NOT NULL,
    message text NOT NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    status text NOT NULL CHECK (status IN ('queued','deferred','skipped','dispatched','completed','failed','expired')),
    reason text NOT NULL,
    command_id text UNIQUE,
    completed_at timestamptz,
    attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    dispatch_deadline timestamptz,
    last_error_code text,
    next_attempt_at timestamptz,
    version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
    UNIQUE (device_id, event_id, topic)
);
CREATE INDEX IF NOT EXISTS proactive_messages_claim ON proactive_messages(device_id,created_at,id) WHERE status='queued';
CREATE INDEX IF NOT EXISTS proactive_messages_quota ON proactive_messages(device_id,created_at DESC) WHERE status IN ('queued','dispatched','completed','failed');
CREATE INDEX IF NOT EXISTS proactive_messages_timeout ON proactive_messages(dispatch_deadline) WHERE status='dispatched';

CREATE TABLE IF NOT EXISTS trigger_candidates (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id uuid NOT NULL REFERENCES manual_events(id) ON DELETE RESTRICT,
    event_revision integer NOT NULL CHECK (event_revision >= 1),
    device_id text NOT NULL,
    dedupe_key text NOT NULL,
    title text NOT NULL,
    message text NOT NULL,
    eligible_at timestamptz NOT NULL,
    expires_at timestamptz NOT NULL,
    status text NOT NULL CHECK (status IN ('pending','deferred','consumed','cancelled','expired')),
    reason text NOT NULL,
    message_id bigint REFERENCES proactive_messages(id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    UNIQUE (device_id, dedupe_key),
    CHECK (expires_at > eligible_at)
);
CREATE INDEX IF NOT EXISTS trigger_candidates_ready ON trigger_candidates(eligible_at,id) WHERE status IN ('pending','deferred');

CREATE TABLE IF NOT EXISTS proactive_policy (
    device_id text PRIMARY KEY,
    enabled boolean NOT NULL DEFAULT false,
    timezone text NOT NULL DEFAULT 'Asia/Shanghai' CHECK (timezone='Asia/Shanghai'),
    quiet_start time NOT NULL DEFAULT TIME '23:30',
    quiet_end time NOT NULL DEFAULT TIME '08:00',
    daily_max integer NOT NULL DEFAULT 2 CHECK (daily_max BETWEEN 0 AND 20),
    cooldown_minutes integer NOT NULL DEFAULT 240 CHECK (cooldown_minutes BETWEEN 0 AND 1440),
    version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS dispatch_attempts (
    command_id text PRIMARY KEY,
    message_id bigint NOT NULL REFERENCES proactive_messages(id) ON DELETE RESTRICT,
    attempt_number integer NOT NULL CHECK (attempt_number >= 1),
    status text NOT NULL CHECK (status IN ('dispatched','completed','failed','unknown')),
    dispatched_at timestamptz NOT NULL,
    dispatch_deadline timestamptz NOT NULL,
    reported_at timestamptz,
    error_code text,
    UNIQUE (message_id, attempt_number)
);
CREATE INDEX IF NOT EXISTS dispatch_attempts_message ON dispatch_attempts(message_id,attempt_number);
