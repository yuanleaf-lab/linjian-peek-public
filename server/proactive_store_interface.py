"""Backend-neutral persistence contract for proactive messages."""
from typing import Callable, Protocol, runtime_checkable


@runtime_checkable
class ProactiveStoreProtocol(Protocol):
    def get(self, device_id: str, event_id: str, topic: str) -> dict | None: ...
    def get_policy(self, device_id: str) -> dict | None: ...
    def set_policy(self, device_id: str, changes: dict, now: str) -> dict: ...
    def create_manual_event(self, data: dict, now: str) -> dict: ...
    def get_manual_event(self, event_id: str) -> dict | None: ...
    def list_due_manual_events(self, now: str, limit: int = 100) -> list[dict]: ...
    def update_manual_event(self, event_id: str, data: dict, now: str) -> dict: ...
    def cancel_manual_event(self, event_id: str, now: str) -> dict | None: ...
    def materialize_due_candidates(self, events: list[dict], now: str) -> int: ...
    def list_ready_candidates(self, now: str, limit: int = 100) -> list[dict]: ...
    def list_attempts(self, message_id: int) -> list[dict]: ...
    def recent(self, device_id: str, topic: str, day_start: str, now: str) -> dict: ...
    def schedule(self, candidate: dict, day_start: str, now: str, daily_max: int, evaluate: Callable[[dict], tuple[str, str]]) -> dict: ...
    def claim(self, device_id: str, command_id: str, now: str) -> dict | None: ...
    def report(self, command_id: str, ok: bool, now: str, error_code: str = "") -> int: ...
    def recover_timeouts(self, now: str) -> int: ...
    def expire(self, now: str) -> int: ...
